#!/usr/bin/env bash
# Installs the NetworkManager dispatcher hook(s) in this directory into
# /etc/NetworkManager/dispatcher.d/.
#
# These are system files (owned by root) and therefore cannot be managed with
# GNU Stow like the rest of this repo, which only symlinks into $HOME. This
# installer copies them into place imperatively, the same way system_setup.sh
# handles other system-level configuration.
set -euo pipefail

# Get the directory of this script.
SOURCE="${BASH_SOURCE[0]}"
while [ -h "$SOURCE" ]; do
	DIR="$(cd -P "$(dirname "$SOURCE")" && pwd)"
	SOURCE="$(readlink "$SOURCE")"
	[[ $SOURCE != /* ]] && SOURCE="$DIR/$SOURCE"
done
DIR="$(cd -P "$(dirname "$SOURCE")" && pwd)"

DEST_DIR=/etc/NetworkManager/dispatcher.d
CONFIG_DEST=/etc/default/bluetooth-home-connect
LOCAL_CONFIG="$DIR/bluetooth-home-connect.conf"
EXAMPLE_CONFIG="$DIR/bluetooth-home-connect.conf.example"

echo "Installing NetworkManager dispatcher hooks into $DEST_DIR..."

# NetworkManager only runs dispatcher scripts that are owned by root and are
# not writable by group/other, so install them root-owned with mode 0755.
sudo install -m 0755 -o root -g root "$DIR/90-bluetooth-home" "$DEST_DIR/90-bluetooth-home"

echo "Installed:"
ls -la "$DEST_DIR/90-bluetooth-home"

# --- config generation -------------------------------------------------------

# Detect the current default gateway (router) MAC address(es). Prints one
# "mac<TAB>gateway_ip" line per default route.
detect_gateway_macs() {
	local gws gw mac
	mapfile -t gws < <(ip route show default 2>/dev/null | awk '{print $3}' | sort -u)
	for gw in "${gws[@]}"; do
		ping -c1 -W1 "$gw" >/dev/null 2>&1 || true
		mac=$(ip neigh show "$gw" 2>/dev/null | awk '{print tolower($5)}' | grep -E '^([0-9a-f]{2}:){5}[0-9a-f]{2}$' | head -n1)
		[ -n "$mac" ] && printf '%s\t%s\n' "$mac" "$gw"
	done
}

# Interactively build $LOCAL_CONFIG from the current network and paired
# Bluetooth devices.
generate_config() {
	local gw_macs=() dev_macs=() dev_names=()

	# --- home router --------------------------------------------------------
	echo
	echo "Detecting current network (this should be your home network)..."
	local -a detected=()
	mapfile -t detected < <(detect_gateway_macs)

	if [ "${#detected[@]}" -gt 0 ]; then
		local line mac gw conn
		for line in "${detected[@]}"; do
			mac=${line%%$'\t'*}
			gw=${line#*$'\t'}
			conn=$(nmcli -t -f NAME connection show --active 2>/dev/null | head -n1)
			read -r -p "Use gateway $gw (router MAC $mac${conn:+, via \"$conn\"}) as home? [Y/n]: " ans
			ans=${ans:-Y}
			[[ $ans =~ ^[yY] ]] && gw_macs+=("$mac")
		done
	else
		echo "Could not auto-detect a gateway MAC (are you connected to your home network?)."
	fi

	# Allow manual entry if nothing was detected/accepted.
	while [ "${#gw_macs[@]}" -eq 0 ]; do
		read -r -p "Enter your home router MAC manually (aa:bb:cc:dd:ee:ff), or blank to abort: " mac
		mac=$(printf '%s' "$mac" | tr 'A-Z' 'a-z')
		if [ -z "$mac" ]; then
			return 1
		elif [[ $mac =~ ^([0-9a-f]{2}:){5}[0-9a-f]{2}$ ]]; then
			gw_macs+=("$mac")
		else
			echo "  Not a valid MAC address."
		fi
	done

	# --- Bluetooth devices --------------------------------------------------
	echo
	if command -v bluetoothctl >/dev/null 2>&1; then
		echo "Looking for known Bluetooth devices..."
		local -a bt=()
		mapfile -t bt < <(bluetoothctl devices 2>/dev/null | sed -n 's/^Device //p')
		if [ "${#bt[@]}" -gt 0 ]; then
			local i
			for i in "${!bt[@]}"; do
				printf "  %2d) %s\n" "$((i + 1))" "${bt[$i]}"
			done
			read -r -p "Select device(s) to auto-connect at home [e.g. \"1 3\", 'a' for all, blank to skip]: " sel
			local -a picks=()
			if [ "$sel" = "a" ] || [ "$sel" = "A" ]; then
				for i in "${!bt[@]}"; do picks+=("$i"); done
			else
				local n
				for n in $sel; do
					[[ $n =~ ^[0-9]+$ ]] && [ "$n" -ge 1 ] && [ "$n" -le "${#bt[@]}" ] && picks+=("$((n - 1))")
				done
			fi
			for i in "${picks[@]}"; do
				local entry devmac devname
				entry=${bt[$i]}
				devmac=${entry%% *}
				devname=${entry#* }
				dev_macs+=("$devmac")
				dev_names+=("$devname")
				# Trusting is required for BlueZ to auto-connect the device.
				bluetoothctl trust "$devmac" >/dev/null 2>&1 || true
			done
		else
			echo "No known Bluetooth devices found. Pair and trust one, then re-run."
		fi
	else
		echo "bluetoothctl not found; skipping Bluetooth device selection."
	fi

	# --- write config -------------------------------------------------------
	{
		echo "# Local configuration for the 90-bluetooth-home dispatcher hook."
		echo "# Generated by networkmanager/install.sh on $(date -Is)."
		echo "# This file is gitignored; keep real MAC addresses out of the public repo."
		echo "# Sourced by bash."
		echo
		echo "# Home router (default gateway) MAC allowlist (lowercase)."
		echo "HOME_GATEWAY_MACS=("
		local m
		for m in "${gw_macs[@]}"; do printf '\t"%s"\n' "$m"; done
		echo ")"
		echo
		echo "# Bluetooth devices to auto-connect (MAC  # name). Must be paired and trusted."
		echo "BT_DEVICES=("
		local i
		for i in "${!dev_macs[@]}"; do printf '\t"%s" # %s\n' "${dev_macs[$i]}" "${dev_names[$i]}"; done
		echo ")"
	} >"$LOCAL_CONFIG"

	echo
	echo "Wrote $LOCAL_CONFIG:"
	sed 's/^/  /' "$LOCAL_CONFIG"
	return 0
}

# Decide whether to (re)generate the local config.
echo
if [ -f "$LOCAL_CONFIG" ]; then
	read -r -p "A local config already exists. Regenerate from the current network/devices? [y/N]: " ans
	ans=${ans:-N}
	[[ $ans =~ ^[yY] ]] && { generate_config || echo "Config generation aborted; keeping existing $LOCAL_CONFIG."; }
else
	read -r -p "Auto-generate config from the current router and Bluetooth devices? [Y/n]: " ans
	ans=${ans:-Y}
	[[ $ans =~ ^[yY] ]] && { generate_config || echo "Config generation aborted."; }
fi

# Deploy the local config (real MAC addresses). It lives outside the tracked
# repo files so personal data is not published. Mode 0600 keeps the router MAC
# readable only by root (the dispatcher runs as root).
echo
if [ -f "$LOCAL_CONFIG" ]; then
	echo "Installing local config into $CONFIG_DEST..."
	sudo install -m 0600 -o root -g root "$LOCAL_CONFIG" "$CONFIG_DEST"
	ls -la "$CONFIG_DEST"
elif [ ! -e "$CONFIG_DEST" ]; then
	echo "No local config; installing the example template to $CONFIG_DEST — EDIT it with your values:"
	sudo install -m 0600 -o root -g root "$EXAMPLE_CONFIG" "$CONFIG_DEST"
	ls -la "$CONFIG_DEST"
else
	echo "Keeping existing $CONFIG_DEST."
fi

echo
echo "Done. The hook runs on network up/change and connects the configured"
echo "Bluetooth device(s) when on the home network (matched by gateway MAC)."
